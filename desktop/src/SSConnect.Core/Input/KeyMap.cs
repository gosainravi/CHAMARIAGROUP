using System.Collections.Generic;

namespace SSConnect.Core.Input
{
    // The wire always carries Windows virtual-key codes. The Mac app translates to and from macOS key codes.
    // Ctrl is sent as Command on the Mac (and Command as Ctrl to Windows), so copy/paste shortcuts feel native
    // on both sides; the Windows key maps to the Mac Control key.
    public static class KeyMap
    {
        static readonly Dictionary<int, int> VkMac = new Dictionary<int, int>
        {
            [0x41] = 0x00, [0x53] = 0x01, [0x44] = 0x02, [0x46] = 0x03, [0x48] = 0x04, [0x47] = 0x05, [0x5A] = 0x06,
            [0x58] = 0x07, [0x43] = 0x08, [0x56] = 0x09, [0x42] = 0x0B, [0x51] = 0x0C, [0x57] = 0x0D, [0x45] = 0x0E,
            [0x52] = 0x0F, [0x59] = 0x10, [0x54] = 0x11, [0x4F] = 0x1F, [0x55] = 0x20, [0x49] = 0x22, [0x50] = 0x23,
            [0x4C] = 0x25, [0x4A] = 0x26, [0x4B] = 0x28, [0x4E] = 0x2D, [0x4D] = 0x2E,
            [0x31] = 0x12, [0x32] = 0x13, [0x33] = 0x14, [0x34] = 0x15, [0x36] = 0x16, [0x35] = 0x17, [0x39] = 0x19,
            [0x37] = 0x1A, [0x38] = 0x1C, [0x30] = 0x1D,
            [0xBB] = 0x18, [0xBD] = 0x1B, [0xDD] = 0x1E, [0xDB] = 0x21, [0xDE] = 0x27, [0xBA] = 0x29, [0xDC] = 0x2A,
            [0xBC] = 0x2B, [0xBF] = 0x2C, [0xBE] = 0x2F, [0xC0] = 0x32,
            [0x0D] = 0x24, [0x09] = 0x30, [0x20] = 0x31, [0x08] = 0x33, [0x1B] = 0x35,
            [0x11] = 0x37, [0x10] = 0x38, [0x14] = 0x39, [0x12] = 0x3A, [0x5B] = 0x3B,
            [0x70] = 0x7A, [0x71] = 0x78, [0x72] = 0x63, [0x73] = 0x76, [0x74] = 0x60, [0x75] = 0x61, [0x76] = 0x62,
            [0x77] = 0x64, [0x78] = 0x65, [0x79] = 0x6D, [0x7A] = 0x67, [0x7B] = 0x6F,
            [0x24] = 0x73, [0x21] = 0x74, [0x2E] = 0x75, [0x23] = 0x77, [0x22] = 0x79,
            [0x25] = 0x7B, [0x27] = 0x7C, [0x28] = 0x7D, [0x26] = 0x7E,
        };

        static readonly Dictionary<int, int> MacVk = Invert(VkMac);

        public static int VkToMac(int vk) => VkMac.TryGetValue(vk, out var m) ? m : -1;
        public static int MacToVk(int mac) => MacVk.TryGetValue(mac, out var v) ? v : -1;

        static Dictionary<int, int> Invert(Dictionary<int, int> d)
        {
            var r = new Dictionary<int, int>();
            foreach (var kv in d) r[kv.Value] = kv.Key;
            return r;
        }
    }
}
